// Arc TESTNET staging deployment — for pre-mainnet verification only.
// This is NOT the hackathon submission path; that's script/deploy.js,
// which only ever targets the `arc` (mainnet) network.
//
// IMPORTANT: this only works while src/Vault.sol and src/VaultFactory.sol
// have their CHAIN_ID constant temporarily set to Arc testnet's chain ID
// (5042002) instead of the real mainnet value (5042). That substitution is
// deliberately never committed — see memory.md Decision 8. Restore both
// files to CHAIN_ID = 5042 and recompile before any mainnet action.
//
// Usage:
//   npx hardhat run script/deploy-testnet.js --network arcTestnet
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");

async function main() {
  if (network.name !== "arcTestnet") {
    throw new Error(`Refusing to run on network "${network.name}". Use --network arcTestnet.`);
  }

  const usdcAddress = process.env.ARC_USDC_ADDRESS;
  if (!usdcAddress) throw new Error("ARC_USDC_ADDRESS is not set in .env");

  const [deployer] = await ethers.getSigners();
  console.log("Deploying to Arc testnet as", deployer.address);

  const usdc = new ethers.Contract(
    usdcAddress,
    ["function balanceOf(address) view returns (uint256)", "function decimals() view returns (uint8)"],
    ethers.provider
  );
  const [balance, decimals] = await Promise.all([usdc.balanceOf(deployer.address), usdc.decimals()]);
  console.log(`Deployer testnet USDC balance: ${ethers.formatUnits(balance, decimals)}`);
  if (balance === 0n) {
    throw new Error(
      `Deployer has 0 testnet USDC. Fund ${deployer.address} from https://faucet.circle.com first.`
    );
  }

  const Factory = await ethers.getContractFactory("VaultFactory");
  const factory = await Factory.deploy(usdcAddress);
  await factory.waitForDeployment();
  const factoryAddress = await factory.getAddress();
  console.log("VaultFactory (testnet) deployed at:", factoryAddress);

  const outPath = path.join(__dirname, "..", "frontend", "src", "deployedTestnet.js");
  fs.writeFileSync(
    outPath,
    `// Auto-generated by script/deploy-testnet.js against Arc's public testnet
// (chain ID 5042002). This is a staging deployment for a hosted preview
// only — the real hackathon submission targets Arc mainnet via
// script/deploy.js, which this file has no connection to.
export default {
  factory: "${factoryAddress}",
};
`
  );
  console.log("Wrote frontend/src/deployedTestnet.js");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
