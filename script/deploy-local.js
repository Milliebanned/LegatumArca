// Local-testing-only deployment. Deploys MockUSDC + VaultFactory to
// whatever network this is run against (intended: `localhost`, i.e. a
// `npx hardhat node` instance, which hardhat.config.js pins to chain ID
// 5042 so it satisfies the same "Arc mainnet only" checks the real
// contracts enforce). Also mints test USDC to the deployer and writes the
// deployed addresses to frontend/src/deployedLocal.js so the frontend picks
// them up automatically in dev mode.
//
// This script is NOT part of the Arc mainnet deployment path — that's
// script/deploy.js, which refuses to run anywhere but the `arc` network.
//
// Usage:
//   npx hardhat run script/deploy-local.js --network localhost
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");

async function main() {
  if (network.name === "arc") {
    throw new Error("Refusing to run the local deploy script against the arc network.");
  }

  const [deployer] = await ethers.getSigners();
  console.log(`Deploying to network "${network.name}" as ${deployer.address}`);

  const MockUSDC = await ethers.getContractFactory("MockUSDC");
  const usdc = await MockUSDC.deploy();
  await usdc.waitForDeployment();
  const usdcAddress = await usdc.getAddress();
  console.log("MockUSDC deployed at:", usdcAddress);

  const Factory = await ethers.getContractFactory("VaultFactory");
  const factory = await Factory.deploy(usdcAddress);
  await factory.waitForDeployment();
  const factoryAddress = await factory.getAddress();
  console.log("VaultFactory deployed at:", factoryAddress);

  // Mint test USDC to every local signer so any of them can act as an owner.
  const signers = await ethers.getSigners();
  const mintAmount = ethers.parseUnits("10000", 6);
  for (const signer of signers.slice(0, 5)) {
    await (await usdc.mint(signer.address, mintAmount)).wait();
  }
  console.log(`Minted 10,000 test USDC to ${Math.min(5, signers.length)} local accounts`);

  const outPath = path.join(__dirname, "..", "frontend", "src", "deployedLocal.js");
  const contents = `// Auto-generated by script/deploy-local.js. Local Hardhat-node testing only —
// never used for the Arc mainnet build (see src/config.js).
export default {
  factory: "${factoryAddress}",
  usdc: "${usdcAddress}",
};
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, contents);
  console.log("Wrote frontend/src/deployedLocal.js");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
